// Generates docs/ENGINE_WORKED_EXAMPLE.md from the synthetic fixtures by running the real engine.
// Usage: npm run engine:example   (add --stdout to print instead of writing)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { analyzeLocality, runWhatIf, SERVICES } from '../src/engine/index.js';
import { round } from '../src/engine/util.js';
import { NOW, rohiniScenario, localityA, localityB } from '../tests/fixtures/scenarios.js';

// Round with the engine's own rounding first so every figure matches the engine output.
const fmt = (v, dp = 1) =>
  v === null || v === undefined ? '—' : round(Number(v), dp).toLocaleString('en-IN', { maximumFractionDigits: dp });

function coverageTable(r) {
  const rows = SERVICES.map((s) => {
    const c = r.coverage.byService[s];
    return `| ${c.label} | ${c.unit} | ${fmt(c.required, 2)} | ${c.listed} | ${fmt(c.listedCapacity, 2)} | ${fmt(c.effective, 2)} | ${fmt(c.coveragePct)}% | ${fmt(c.deficitPct)}% | ${fmt(c.weight, 3)} |`;
  });
  return [
    '| Service | Unit | Required | Listed | Listed capacity | Effective | Coverage | Deficit | Weight |',
    '|---|---|---:|---:|---:|---:|---:|---:|---:|',
    ...rows,
    `| **Overall (weighted)** | | | | | | **${fmt(r.coverage.overall.coveragePct)}%** | **${fmt(r.coverage.overall.deficitPct)}%** | |`,
  ].join('\n');
}

function resourceTable(r) {
  const res = SERVICES.flatMap((s) => r.coverage.byService[s].resources);
  if (!res.length) return '_No resources listed._';
  return [
    '| Resource | Capacity | Reliability | Accessibility | Availability × status × freshness | Effective |',
    '|---|---:|---:|---:|---|---:|',
    ...res.map(
      (x) =>
        `| ${x.name ?? x.id} | ${fmt(x.capacity)} ${x.unit} | ${x.reliability} | ${x.accessibility} | ${x.factors.availability} × ${x.factors.status} × ${x.factors.freshness} = ${x.factors.availabilityFactor}${x.stale ? ' (stale)' : !x.verified ? ' (unverified)' : ''} | ${fmt(x.effectiveCapacity, 2)} |`
    ),
  ].join('\n');
}

function factorTable(r) {
  const p = r.priority;
  return [
    '| Factor | Value (0–1) | Weight | Points | Detail |',
    '|---|---:|---:|---:|---|',
    ...p.factors.map((f) => `| ${f.label} | ${fmt(f.value, 4)} | ${fmt(f.weight, 3)} | ${fmt(f.points, 2)} | ${f.detail} |`),
    ...p.modifiers.map((m) => `| Modifier: ${m.label} (${m.count}) | | | ${m.points > 0 ? '+' : ''}${fmt(m.points, 2)} | ${m.rule} |`),
    `| **Score** | | | **${fmt(p.score)}** | **${p.band}**${p.capped ? ' (capped at 100)' : ''} |`,
  ].join('\n');
}

function section(title, r) {
  const h = r.risk.hazard;
  return `## ${title}

${r.explanation.summary}

**Signal:** ${h.signal ? `${h.severity} / ${h.warningLevel}, ${h.status}, issued ${h.hoursSinceIssue} h before \`now\`, trend ${h.trend} (${h.trendSource}). Label: ${h.signal.label}.` : 'none'}
**Hazard** = intensity ${fmt(h.intensity, 4)} × recency ${fmt(h.recency, 4)} × trend ${h.trendMultiplier} = **${fmt(h.value, 4)}**
**Vulnerability** = ${fmt(r.risk.vulnerability.value, 4)} (${r.risk.vulnerability.method})
**Exposure** = ${fmt(r.risk.exposure.value, 4)} (${r.risk.exposure.method})
**Risk score** (no resources) = **${fmt(r.risk.score)}**

### Resources
${resourceTable(r)}

### Coverage
${coverageTable(r)}

### Priority factor breakdown
${factorTable(r)}

### Gaps
${r.gaps.length ? r.gaps.map((g) => `- **${g.code}** (${g.severity}): ${g.message}`).join('\n') : '_None._'}

### Recommended interventions (each needs approval)
${r.interventions.length ? r.interventions.map((a) => `${a.rank}. **${a.code}**: ${a.description} ${a.expectedEffect.priorityReduction > 0 ? `Modelled priority ${fmt(a.expectedEffect.priorityBefore)} → ${fmt(a.expectedEffect.priorityAfter)} (−${fmt(a.expectedEffect.priorityReduction)}).` : 'No modelled score change (improves data confidence).'}`).join('\n') : '_None._'}
`;
}

const opts = { now: NOW };
const rohini = analyzeLocality(rohiniScenario(), opts);
const a = analyzeLocality(localityA(), opts);
const b = analyzeLocality(localityB(), opts);
const whatIf = runWhatIf(
  localityB(),
  [{ op: 'update', id: 'res-b-water-1', patch: { lastVerifiedAt: NOW } }],
  opts
);

const md = `# Engine worked example

> **Demo data. Not an assessment of real localities.** Generated by \`npm run engine:example\` from
> \`backend/tests/fixtures/scenarios.js\` using engine ${rohini.meta.engineVersion}, config \`${rohini.meta.configVersion}\`,
> \`now\` = ${NOW}. Every value below is **Modelled**. Re-run the script after any config change; do not edit by hand.

## A vs B: same warning, different support

| | Ward A | Ward B |
|---|---:|---:|
| Heat signal | ${a.risk.hazard.severity} / ${a.risk.hazard.warningLevel} | ${b.risk.hazard.severity} / ${b.risk.hazard.warningLevel} |
| Population / vulnerable | ${fmt(a.risk.vulnerability.population)} / ${fmt(a.risk.vulnerability.vulnerablePopulation)} | ${fmt(b.risk.vulnerability.population)} / ${fmt(b.risk.vulnerability.vulnerablePopulation)} |
| Risk score (no resources) | ${fmt(a.risk.score)} | ${fmt(b.risk.score)} |
| Overall coverage | ${fmt(a.coverage.overall.coveragePct)}% | ${fmt(b.coverage.overall.coveragePct)}% |
| Deficit points | ${fmt(a.priority.factors.find((f) => f.key === 'deficit').points, 2)} | ${fmt(b.priority.factors.find((f) => f.key === 'deficit').points, 2)} |
| **Priority** | **${fmt(a.priority.score)} ${a.priority.band}** | **${fmt(b.priority.score)} ${b.priority.band}** |

Same risk, different priority: the gap is in the response, not the weather.

**What-if (Modelled, not saved):** re-verifying Ward B's stale water point moves water coverage
${fmt(whatIf.before.coverage.byService.water.coveragePct)}% → ${fmt(whatIf.after.coverage.byService.water.coveragePct)}% and priority
${fmt(whatIf.before.priority.score)} → ${fmt(whatIf.after.priority.score)} (${whatIf.after.priority.band}). \`persisted: ${whatIf.persisted}\`.

${section('Rohini, Delhi (spec demo scenario, synthetic)', rohini)}
Check: 8,000 L/day × 0.75 × 0.65 × 1 = **${fmt(rohini.coverage.byService.water.effective, 2)} L/day** effective;
÷ 25,000 L/day required = **${fmt(rohini.coverage.byService.water.coveragePct)}%** water coverage.

${section('Ward A (demo)', a)}
${section('Ward B (demo)', b)}
## Assumptions in force
${rohini.explanation.assumptions.map((x) => `- ${x}`).join('\n')}

## Limitations
${rohini.explanation.limitations.map((x) => `- ${x}`).join('\n')}
`;

if (process.argv.includes('--stdout')) {
  process.stdout.write(md);
} else {
  const out = fileURLToPath(new URL('../../docs/ENGINE_WORKED_EXAMPLE.md', import.meta.url));
  writeFileSync(out, md);
  console.log(`Wrote ${out}`);
}
